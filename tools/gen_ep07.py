def clip(cid, src, a, b, subs, extra):
    tail = extra.get("pad", 0.0) + extra.get("hold", 0.0)   # 字幕可以延到補的停頓裡（講完約 0.25 秒才收）
    s = [[round(max(t, a) - a, 2), round(min(e, b + tail) - a, 2), txt] for t, e, txt in subs]
    c = {"id": f"#{cid}", "src": f"{src}.MOV", "in": a, "out": b, "subs": s,
         "auto_gain": False, "gain_db": round(TARGET - LUFS[src], 1)}
    if SHIFT.get(src):
        c["shift_y"] = SHIFT[src]
    c.update(extra)
    return c


