def clip(cid, a, b, subs, extra):
    # 字幕可以是 (開始, 文字)（顯示到下一句開始）或 (開始, 結束, 文字)（講完就收）
    s = []
    for k, sub in enumerate(subs):
        t, e, txt = sub if len(sub) == 3 else (sub[0], subs[k + 1][0] if k + 1 < len(subs) else b, sub[1])
        s.append([round(max(t, a) - a, 2), round(min(e, b) - a, 2), txt])
    c = {"id": f"#{cid}", "src": SRC, "in": a, "out": b, "subs": s}
    c.update(extra)
    return c


