def clip(cid, a, b, subs, extra):
    s = [[round(max(t, a) - a, 2), round((subs[k + 1][0] if k + 1 < len(subs) else b) - a, 2), txt]
         for k, (t, txt) in enumerate(subs)]
    c = {"id": f"#{cid}", "src": SRC, "in": a, "out": b, "subs": s}
    c.update(extra)
    return c


