def clip(cid, a, b, subs, extra):
    tail = extra.get("pad", 0.0) + extra.get("hold", 0.0)
    s = [[round(max(t, a) - a, 2), round(min(e, b + tail) - a, 2), txt] for t, e, txt in subs]
    c = {"id": f"#{cid.split()[0]}", "src": SRC, "in": a, "out": b, "subs": s, "shift_y": SHIFT}
    if cid in PAIR_LUFS:
        c.update(auto_gain=False, gain_db=round(TARGET - PAIR_LUFS[cid], 1))
    c.update(extra)
    return c


